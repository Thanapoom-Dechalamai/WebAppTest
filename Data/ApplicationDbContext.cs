    public override async Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
    {
        ChangeTracker.DetectChanges();
        var entries = ChangeTracker.Entries().Where(x=>x.Entity is not AuditLog && x.Entity is not Notification &&
            x.State is EntityState.Added or EntityState.Modified or EntityState.Deleted).ToList();
        if(entries.Count==0) return await base.SaveChangesAsync(cancellationToken);
        var changes = entries.Select(x=> new { Entry=x, Action=x.State.ToString(),
            Old=x.State==EntityState.Added ? null : AuditJson(x.OriginalValues) }).ToList();
        var ownTransaction = Database.CurrentTransaction is null;
        await using var tx = ownTransaction ? await Database.BeginTransactionAsync(cancellationToken) : null;
        try {
            var result=await base.SaveChangesAsync(cancellationToken);
            int? actor=int.TryParse(http.HttpContext?.User.FindFirst(System.Security.Claims.ClaimTypes.NameIdentifier)?.Value,out var id)?id:null;
            foreach(var change in changes) {
                var entry=change.Entry;
                var key=entry.Metadata.FindPrimaryKey()!;
                AuditLogs.Add(new AuditLog {
                    ActorUserId=actor, RequestId=http.HttpContext?.TraceIdentifier ?? "startup",
                    TableName=entry.Metadata.GetTableName()!, Action=change.Action,
                    RecordId=string.Join(",",key.Properties.Select(x=>entry.Property(x.Name).CurrentValue)),
                    OldData=change.Old,
                    NewData=change.Action=="Deleted" ? null : AuditJson(entry.CurrentValues)
                });
            }
            await base.SaveChangesAsync(cancellationToken);
            if(tx is not null) await tx.CommitAsync(cancellationToken);
            return result;
        } catch { if(tx is not null) await tx.RollbackAsync(cancellationToken); throw; }
    }
    private static string AuditJson(Microsoft.EntityFrameworkCore.ChangeTracking.PropertyValues values) =>
        System.Text.Json.JsonSerializer.Serialize(values.Properties.Where(x=>x.Name!="PasswordHash")
            .ToDictionary(x=>x.Name,x=>values[x]));
